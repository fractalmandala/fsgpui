// @fractaldesign/fsgui - Rust Code Generator for GPUI
import type { ResolvedTheme, ColorToken } from '../types.js';
import { toGpuiTheme } from './theme.js';

function toSnakeCase(str: string): string {
	return str.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`).replace(/^_/, '');
}

export function generateRustTokens(theme: ResolvedTheme): string {
	const gpuiTheme = toGpuiTheme(theme);

	const colorFields: string[] = [];
	const colorInits: string[] = [];

	for (const [key, color] of Object.entries(gpuiTheme.colors)) {
		const snake = toSnakeCase(key);
		colorFields.push(`    pub ${snake}: gpui::Rgba,`);
		colorInits.push(`            ${snake}: ${color.rustLiteral},`);
	}

	const spacingConstants: string[] = [];
	for (const [key, space] of Object.entries(gpuiTheme.spacing)) {
		const upper = key.replace(/[-]/g, '_').toUpperCase();
		spacingConstants.push(`pub const SPACE_${upper}: gpui::Pixels = ${space.rustSnippet};`);
	}

	const shapeConstants: string[] = [];
	for (const [key, shape] of Object.entries(gpuiTheme.shapes)) {
		const upper = key.toUpperCase();
		shapeConstants.push(`pub const RADIUS_${upper}: gpui::Pixels = ${shape.rustSnippet};`);
	}

	return `// Generated by @fractaldesign/fsgui - DO NOT EDIT MANUALLY
// GPUI Design Tokens & Theme Specification

#![allow(unused_imports, dead_code)]

use gpui::{self, Pixels, Rgba, px};

/// Complete Fractal Design System theme for GPUI
#[derive(Debug, Clone)]
pub struct FsTheme {
${colorFields.join('\n')}
}

impl Default for FsTheme {
    fn default() -> Self {
        Self {
${colorInits.join('\n')}
        }
    }
}

// Spacing Scale
${spacingConstants.join('\n')}

// Corner Radii (Shapes)
${shapeConstants.join('\n')}

impl FsTheme {
    /// Return the default theme instance
    pub fn new() -> Self {
        Self::default()
    }
}
`;
}
